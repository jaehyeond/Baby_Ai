"""Offline B5 evaluation against the next external user input.

B3 scored a graph prediction against words generated by the LLM in the same
turn.  B4 showed that this was mostly a target-definition failure.  This
module instead evaluates the prediction saved on turn ``t`` against meaningful
concepts in the user's input on turn ``t + 1``.

The evaluator is deliberately read-only.  It does not update Neo4j, the live
learning-progress state, thresholds, or the protected conversation handler.
"""

