SEQUENCE_QUERY = """
UNWIND $experience_ids AS requested_id
MATCH (e:Experience {id: requested_id})
OPTIONAL MATCH (cue:Concept)
WHERE cue.id IN coalesce(e.curiosity_cue_ids, [])
WITH requested_id, e,
     collect(DISTINCT {
       id: cue.id,
       name: cue.name,
       created_at: toString(cue.created_at)
     }) AS cue_concepts
OPTIONAL MATCH (predicted:Concept)
WHERE predicted.id IN coalesce(e.predicted_concept_ids, [])
RETURN requested_id AS experience_id,
       e.task AS task,
       toString(e.created_at) AS created_at,
       cue_concepts,
       collect(DISTINCT {
         id: predicted.id,
         name: predicted.name,
         created_at: toString(predicted.created_at)
       }) AS predicted_concepts
"""

HISTORY_QUERY = """
MATCH (e:Experience)
WHERE e.task_type = 'conversation' AND e.task IS NOT NULL
RETURN e.id AS experience_id,
       e.task AS task,
       toString(e.created_at) AS created_at
ORDER BY e.created_at
"""

CONCEPT_QUERY = """
MATCH (c:Concept)
WHERE c.id IS NOT NULL AND c.name IS NOT NULL
RETURN c.id AS id, c.name AS name, toString(c.created_at) AS created_at
"""

SENSOR_COVERAGE_QUERY = """
CALL () {
  MATCH (e:Experience)
  WHERE e.task_type = 'vision'
  OPTIONAL MATCH (e)-[:INVOLVES]->(observed:Concept)
  WITH e, count(observed) AS observed_count
  RETURN count(e) AS vision_experience_count,
         sum(CASE WHEN observed_count > 0 THEN 1 ELSE 0 END)
           AS vision_with_observed_concepts,
         sum(CASE WHEN size(coalesce(e.predicted_concept_ids, [])) > 0
             THEN 1 ELSE 0 END) AS vision_with_prediction_snapshot
}
CALL () {
  MATCH (:Experience {task_type: 'vision'})-[link:NEXT_FRAME]->
        (:Experience {task_type: 'vision'})
  RETURN count(link) AS next_frame_link_count
}
RETURN vision_experience_count,
       vision_with_observed_concepts,
       vision_with_prediction_snapshot,
       next_frame_link_count
"""

MIN_SCORABLE_PAIRS = 6
MIN_UNIQUE_EXTERNAL_OUTCOMES = 4
MIN_BASELINE_IMPROVED_PAIRS = 3
MIN_GRAPH_HITS = 3
_EXTERNAL_INPUT_FUNCTION_TERMS = frozenset({
    "왜", "어떻게", "어떻", "안녕", "어때", "해", "해줘", "해주세요",
})


def _valid_concepts(items: Iterable[dict[str, Any]]) -> list[dict[str, Any]]:
    return [item for item in items if item and item.get("id") and item.get("name")]


def _parse_timestamp(value: Any) -> datetime | None:
    text = str(value or "").strip()
    if not text:
        return None
    try:
        return datetime.fromisoformat(text.replace("Z", "+00:00"))
    except ValueError:
        return None


def canonical_bucket(name: Any) -> str:
    """Return one deterministic key for B4's conservative equivalence set."""

    forms = conservative_canonical_forms(name)
    if not forms:
        return ""
    hada_forms = sorted(form for form in forms if form.endswith("하다"))
    if hada_forms:
        return hada_forms[0]
    return min(forms, key=lambda form: (len(form), form))


def extract_external_input_terms(message: str) -> list[str]:
    """Mirror endpoint parsing, then remove generic speech-act expressions."""

    extracted = _extract_concepts_from_response("", message or "")
    terms = build_curiosity_cue_terms(
        message or "",
        extracted_terms=extracted,
        max_terms=32,
    )
    return [
        term
        for term in filter_curiosity_cue_terms(terms)
        if normalize_concept_name(term) not in _EXTERNAL_INPUT_FUNCTION_TERMS
    ]


def build_sequence_pairs(
    records: Iterable[dict[str, Any]],
    sequences: Sequence[tuple[str, Sequence[str]]] = B5_SEQUENCES,
) -> tuple[list[dict[str, Any]], list[str]]:
    """Build only within-sequence t -> t+1 pairs and report missing IDs."""

    by_id = {record["experience_id"]: record for record in records}
    requested = [item for _, ids in sequences for item in ids]
    missing = [item for item in requested if item not in by_id]
    pairs: list[dict[str, Any]] = []
    for sequence_name, ids in sequences:
        for source_id, target_id in zip(ids, ids[1:]):
            if source_id not in by_id or target_id not in by_id:
                continue
            pairs.append({
                "sequence": sequence_name,
                "source": by_id[source_id],
                "target": by_id[target_id],
            })
    return pairs, missing


def split_next_input_terms(
    next_message: str,
    cue_concepts: Iterable[dict[str, Any]],
) -> dict[str, list[str]]:
    """Separate meaningful external additions from repeated source cues."""

    terms = extract_external_input_terms(next_message)
    cue_names = [item["name"] for item in _valid_concepts(cue_concepts)]
    repeated: list[str] = []
    external: list[str] = []
    for term in terms:
        if any(is_cue_surface_variant(term, cue_name) for cue_name in cue_names):
            repeated.append(term)
        else:
            external.append(term)
    return {"all_terms": terms, "repeated_cue_terms": repeated, "external_terms": external}


def _available_vocabulary(
    concepts: Iterable[dict[str, Any]],
    source_created_at: Any,
    cue_concepts: Iterable[dict[str, Any]],
) -> dict[str, list[dict[str, Any]]]:
    source_time = _parse_timestamp(source_created_at)
    cue_names = [item["name"] for item in _valid_concepts(cue_concepts)]
    vocabulary: dict[str, list[dict[str, Any]]] = {}
    if source_time is None:
        return vocabulary

    for concept in _valid_concepts(concepts):
        concept_time = _parse_timestamp(concept.get("created_at"))
        if concept_time is None or concept_time > source_time:
            continue
        if any(
            is_cue_surface_variant(concept["name"], cue_name)
            for cue_name in cue_names
        ):
            continue
        key = canonical_bucket(concept["name"])
        if key:
            vocabulary.setdefault(key, []).append(concept)
    return vocabulary


def split_preexisting_outcomes(
    outcome_terms: Iterable[str],
    vocabulary: dict[str, list[dict[str, Any]]],
) -> dict[str, list[str]]:
    preexisting: list[str] = []
    novel: list[str] = []
    for term in outcome_terms:
        key = canonical_bucket(term)
        if key and key in vocabulary:
            preexisting.append(term)
        else:
            novel.append(term)
    return {"preexisting": preexisting, "novel": novel}


def compute_name_prediction_error(
    predicted_names: Iterable[str],
    actual_names: Iterable[str],
) -> float | None:
    """Return name-level recall error using only B4 conservative matches."""

    predicted = list(dict.fromkeys(name for name in predicted_names if name))
    actual = list(dict.fromkeys(name for name in actual_names if name))
    if not actual:
        return None
    hits = sum(
        1
        for actual_name in actual
        if any(
            conservative_name_match(predicted_name, actual_name)
            for predicted_name in predicted
        )
    )
    return round(1.0 - hits / len(actual), 6)


def frequency_baseline_predictions(
    history: Iterable[dict[str, Any]],
    source_created_at: Any,
    vocabulary: dict[str, list[dict[str, Any]]],
    *,
    limit: int,
) -> list[str]:
    """Top historical user-input terms available strictly before the source."""

    source_time = _parse_timestamp(source_created_at)
    if source_time is None or limit <= 0:
        return []

    counts: Counter[str] = Counter()
    first_surface: dict[str, str] = {}
    for record in history:
        record_time = _parse_timestamp(record.get("created_at"))
        if record_time is None or record_time >= source_time:
            continue
        for term in extract_external_input_terms(str(record.get("task") or "")):
            key = canonical_bucket(term)
            if not key or key not in vocabulary:
                continue
            counts[key] += 1
            first_surface.setdefault(key, term)

    ranked = sorted(counts, key=lambda key: (-counts[key], key))[:limit]
    return [first_surface[key] for key in ranked]


def expected_random_error(*, vocabulary_size: int, prediction_count: int) -> float | None:
    """Expected recall error for uniform top-k sampling without replacement."""

    if vocabulary_size <= 0:
        return None
    recall = min(max(prediction_count, 0), vocabulary_size) / vocabulary_size
    return round(1.0 - recall, 6)


def evaluate_pair(
    pair: dict[str, Any],
    concepts: Iterable[dict[str, Any]],
    history: Iterable[dict[str, Any]],
) -> dict[str, Any]:
    source = pair["source"]
    target = pair["target"]
    cues = _valid_concepts(source.get("cue_concepts") or [])
    invalid_cue_names = [
        item["name"]
        for item in cues
        if normalize_concept_name(item["name"]) in _EXTERNAL_INPUT_FUNCTION_TERMS
    ]
    predictions = _valid_concepts(source.get("predicted_concepts") or [])
    predicted_names = [item["name"] for item in predictions]
    term_split = split_next_input_terms(str(target.get("task") or ""), cues)
    vocabulary = _available_vocabulary(concepts, source.get("created_at"), cues)
    outcome_split = split_preexisting_outcomes(term_split["external_terms"], vocabulary)
    scorable = outcome_split["preexisting"]
    frequency_names = frequency_baseline_predictions(
        history,
        source.get("created_at"),
        vocabulary,
        limit=len(predicted_names),
    )
    return {
        "sequence": pair["sequence"],
        "source_experience_id": source["experience_id"],
        "target_experience_id": target["experience_id"],
        "source_task": source.get("task"),
        "next_user_input": target.get("task"),
        "cue_names": [item["name"] for item in cues],
        "invalid_cue_names": invalid_cue_names,
        "predicted_names": predicted_names,
        "next_input_terms": term_split["all_terms"],
        "repeated_cue_terms": term_split["repeated_cue_terms"],
        "external_outcome_terms": term_split["external_terms"],
        "preexisting_outcome_terms": scorable,
        "novel_outcome_terms": outcome_split["novel"],
        "frequency_baseline_names": frequency_names,
        "available_vocabulary_size": len(vocabulary),
        "graph_error": compute_name_prediction_error(predicted_names, scorable),
        "frequency_error": compute_name_prediction_error(frequency_names, scorable),
        "random_expected_error": (
            expected_random_error(
                vocabulary_size=len(vocabulary),
                prediction_count=len(predicted_names),
            )
            if scorable else None
        ),
    }


def _mean(values: Iterable[float | None]) -> float | None:
    present = [float(value) for value in values if value is not None]
    return round(sum(present) / len(present), 6) if present else None


def _hit_count(error: float | None, actual_count: int) -> int:
    if error is None or actual_count <= 0:
        return 0
    return int(round((1.0 - float(error)) * actual_count))


def summarize_evaluation(
    pairs: Iterable[dict[str, Any]],
    concepts: Iterable[dict[str, Any]],
    history: Iterable[dict[str, Any]],
    *,
    missing_experience_ids: Iterable[str] = (),
    sensor_coverage: dict[str, Any] | None = None,
) -> dict[str, Any]:
    missing_ids = list(missing_experience_ids)
    sensor = dict(sensor_coverage or {})
    sensor_route_scorable = bool(
        int(sensor.get("vision_with_prediction_snapshot") or 0) > 0
        and int(sensor.get("next_frame_link_count") or 0) > 0
    )
    evaluated = [evaluate_pair(pair, concepts, history) for pair in pairs]
    contaminated = [item for item in evaluated if item.get("invalid_cue_names")]
    scorable = [
        item
        for item in evaluated
        if item["graph_error"] is not None and not item.get("invalid_cue_names")
    ]
    unique_outcomes = {
        canonical_bucket(term)
        for item in scorable
        for term in item["preexisting_outcome_terms"]
        if canonical_bucket(term)
    }
    graph_mean = _mean(item["graph_error"] for item in scorable)
    frequency_mean = _mean(item["frequency_error"] for item in scorable)
    random_mean = _mean(item["random_expected_error"] for item in scorable)
    paired = [
        item for item in scorable
        if item["graph_error"] is not None and item["frequency_error"] is not None
    ]
    improved_pair_count = sum(
        item["graph_error"] < item["frequency_error"] for item in paired
    )
    tied_pair_count = sum(
        item["graph_error"] == item["frequency_error"] for item in paired
    )
    worsened_pair_count = sum(
        item["graph_error"] > item["frequency_error"] for item in paired
    )
    graph_hit_count = sum(
        _hit_count(item["graph_error"], len(item["preexisting_outcome_terms"]))
        for item in scorable
    )
    frequency_hit_count = sum(
        _hit_count(item["frequency_error"], len(item["preexisting_outcome_terms"]))
        for item in scorable
    )
    data_gate = (
        len(scorable) >= MIN_SCORABLE_PAIRS
        and len(unique_outcomes) >= MIN_UNIQUE_EXTERNAL_OUTCOMES
        and not missing_ids
    )
    baseline_gate = (
        graph_mean is not None
        and frequency_mean is not None
        and random_mean is not None
        and graph_mean < frequency_mean
        and graph_mean < random_mean
    )
    robustness_gate = (
        improved_pair_count >= MIN_BASELINE_IMPROVED_PAIRS
        and graph_hit_count >= MIN_GRAPH_HITS
        and improved_pair_count > worsened_pair_count
    )
    promotion_gate = data_gate and baseline_gate and robustness_gate
    if not data_gate:
        verdict = "insufficient_external_outcome_data"
    elif not baseline_gate:
        verdict = "graph_did_not_beat_baselines"
    elif not robustness_gate:
        verdict = "positive_but_not_robust"
    else:
        verdict = "offline_gate_passed"

    return {
        "database_writes": False,
        "pair_count": len(evaluated),
        "scorable_pair_count": len(scorable),
        "unscorable_pair_count": len(evaluated) - len(scorable),
        "contaminated_pair_count": len(contaminated),
        "preexisting_external_outcome_count": sum(
            len(item["preexisting_outcome_terms"]) for item in evaluated
        ),
        "novel_external_outcome_count": sum(
            len(item["novel_outcome_terms"]) for item in evaluated
        ),
        "unique_preexisting_external_outcome_count": len(unique_outcomes),
        "graph_mean_error": graph_mean,
        "frequency_mean_error": frequency_mean,
        "random_expected_mean_error": random_mean,
        "data_gate": data_gate,
        "baseline_gate": baseline_gate,
        "robustness_gate": robustness_gate,
        "promotion_gate": promotion_gate,
        "verdict": verdict,
        "minimum_scorable_pairs": MIN_SCORABLE_PAIRS,
        "minimum_unique_external_outcomes": MIN_UNIQUE_EXTERNAL_OUTCOMES,
        "minimum_baseline_improved_pairs": MIN_BASELINE_IMPROVED_PAIRS,
        "minimum_graph_hits": MIN_GRAPH_HITS,
        "graph_better_than_frequency_pair_count": improved_pair_count,
        "graph_tied_with_frequency_pair_count": tied_pair_count,
        "graph_worse_than_frequency_pair_count": worsened_pair_count,
        "graph_hit_count": graph_hit_count,
        "frequency_hit_count": frequency_hit_count,
        "missing_experience_ids": missing_ids,
        "sensor_route_scorable": sensor_route_scorable,
        "sensor_coverage": sensor,
        "pairs": evaluated,
    }


async def fetch_inputs(
    driver: Any,
    *,
    database: str,
) -> tuple[
    list[dict[str, Any]],
    list[dict[str, Any]],
    list[dict[str, Any]],
    dict[str, Any],
]:
    experience_ids = [item for _, ids in B5_SEQUENCES for item in ids]
    async with driver.session(database=database) as session:
        result = await session.run(SEQUENCE_QUERY, experience_ids=experience_ids)
        sequence_records = [dict(record) for record in await result.fetch(len(experience_ids))]

        result = await session.run(HISTORY_QUERY)
        history_records = [dict(record) async for record in result]

        result = await session.run(CONCEPT_QUERY)
        concept_records = [dict(record) async for record in result]

        result = await session.run(SENSOR_COVERAGE_QUERY)
        sensor_record = await result.single()
    return (
        sequence_records,
        history_records,
        concept_records,
        dict(sensor_record) if sensor_record else {},
    )


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Read-only B5 next-user-input evaluation",
    )
    parser.add_argument(
        "--compact",
        action="store_true",
        help="omit per-pair details from printed JSON",
    )
    return parser.parse_args()


async def _run() -> dict[str, Any]:
    load_dotenv(PROJECT_ROOT / ".env")
    required = {
        "NEO4J_URI": os.getenv("NEO4J_URI"),
        "NEO4J_USERNAME": os.getenv("NEO4J_USERNAME"),
        "NEO4J_PASSWORD": os.getenv("NEO4J_PASSWORD"),
        "NEO4J_DATABASE": os.getenv("NEO4J_DATABASE"),
    }
    missing = [name for name, value in required.items() if not value]
    if missing:
        raise RuntimeError(f"missing environment keys: {', '.join(missing)}")

    driver = AsyncGraphDatabase.driver(
        required["NEO4J_URI"],
        auth=(required["NEO4J_USERNAME"], required["NEO4J_PASSWORD"]),
    )
    try:
        await driver.verify_connectivity()
        sequence_records, history, concepts, sensor_coverage = await fetch_inputs(
            driver,
            database=str(required["NEO4J_DATABASE"]),
        )
    finally:
        await driver.close()

    pairs, missing_ids = build_sequence_pairs(sequence_records)
    return summarize_evaluation(
        pairs,
        concepts,
        history,
        missing_experience_ids=missing_ids,
        sensor_coverage=sensor_coverage,
    )


def main() -> None:
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")
    args = _parse_args()
    report = asyncio.run(_run())
    if args.compact:
        report = {key: value for key, value in report.items() if key != "pairs"}
    print(json.dumps(report, ensure_ascii=False, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
